import React from "react";
import { Typography } from "@mui/material";
import ModalComponent from "../../../../components/ui/ModalComponent";
import FieldsComponent from "../../../../components/ui/FieldsComponent";
import { cardTitle, cardTypeLabel } from "../../../../lib/cards";
import { formatDateTimePH } from "../../../../lib/time";

/* ₱ amounts — same formatter every page uses. */
const money = (value) =>
  new Intl.NumberFormat("en-PH", { style: "currency", currency: "PHP" }).format(
    Number(value) || 0
  );

/* Spendable figure for a card — the rule the payment choosers use: a
   debit card holds money (dBalance), a credit card offers headroom
   (dAvailable). */
const spendableOf = (card) =>
  Number(card.cType === "C" ? card.dAvailable : card.dBalance) || 0;

/**
 * Which cards the picker offers, per transaction type:
 *   Expense  ("E") — every card: money OUT of it (a plain spend, or a
 *                    savings deposit paid from the card),
 *   Income   ("I") — DEBIT cards only: income landing on a card tops
 *                    up a debit balance (the server rejects a credit),
 *   Purchase ("B") — every card: a purchase is what a card was spent
 *                    on, debit or credit.
 * Returns [] when the field should not render.
 */
function cardsForType(cards, cType) {
  if (cType === "I") return cards.filter((card) => card.cType === "D");
  if (cType === "B" || cType === "E") return cards;
  return [];
}

const getFormFields = (cards = [], formData = {}) => {
  const cType = formData.cType || "I";
  const pickable = cardsForType(cards, cType);
  const isPurchase = cType === "B";
  const chargesCard = cType === "B" || cType === "E";

  /* Balance of the picked card vs the typed amount, shown under the
     selector so sufficiency reads at a glance (display only — it does
     not block the save). The verdict applies only where money LEAVES
     the card (Expense / Purchase); Income tops the card up instead. */
  const selectedCard = pickable.find(
    (card) => String(card.nCardId) === String(formData.nCardId)
  );
  const amount = Number(formData.dAmount) || 0;
  const spendable = selectedCard ? spendableOf(selectedCard) : null;
  const judging = Boolean(selectedCard) && chargesCard && amount > 0;
  const short = judging && spendable < amount;

  return [
    { name: "strTitle", label: "Title", required: true, gridCols: 12, placeholder: "e.g. Freelance project payment" },
    {
      name: "cType",
      label: "Type",
      type: "select",
      required: true,
      gridCols: pickable.length > 0 ? 6 : 12,
      /* Only Income, Expense and Purchase can be typed by hand: P
         (loan) and S (savings) rows are generated by their own tabs and
         stay locked (greyed-out actions) in the table. */
      options: [
        { label: "Income", value: "I" },
        { label: "Expense", value: "E" },
        { label: "Purchase", value: "B" },
      ],
    },
    {
      name: "dAmount",
      label: "Amount",
      type: "peso",
      required: true,
      gridCols: pickable.length > 0 ? 6 : 12,
      placeholder: "0.00",
    },
    /* The card field exists for Income, Expense and Purchase (see
       cardsForType) — linking a card writes tbltransactions.nCardId,
       which is what the Cards tab computes balances from. */
    ...(pickable.length > 0
      ? [
          {
            name: "nCardId",
            label: chargesCard ? "Card used" : "Debit card",
            type: "select",
            gridCols: 12,
            options: [
              { label: "None", value: "" },
              ...pickable.map((card) => ({
                label: `${cardTitle(card)} (${cardTypeLabel(card.cType)}) · ${money(spendableOf(card))}`,
                value: String(card.nCardId),
              })),
            ],
            helperText: !selectedCard ? (
              isPurchase
                ? "The card this purchase was charged to"
                : chargesCard
                  ? "The card this expense was paid from"
                  : "The debit card this income was paid into"
            ) : (
              <span style={{ color: short ? "#f44336" : undefined }}>
                {`${selectedCard.cType === "C" ? "Available credit" : "Balance"}: ${money(spendable)}`}
                {judging
                  ? short
                    ? " · Insufficient"
                    : " · sufficient for this amount"
                  : ""}
              </span>
            ),
          },
        ]
      : []),
    {
      name: "strDescription",
      label: "Description",
      multiline: true,
      rows: 3,
      gridCols: 12,
      placeholder: "Optional notes about this transaction",
    },
  ];
};

/**
 * Add/Edit dialog for an Income/Expense/Purchase transaction.
 * `strCode` is auto-generated by the server (TXN-0001, ...) — it is
 * shown here when editing but is never sent back. `nCardId` (optional)
 * links the row to a card from the Cards tab — offered for Income
 * (debit cards), Expense and Purchase (any card). The card selector
 * lists each card's balance and, for money leaving the card, flags
 * whether that balance covers the typed amount.
 */
export default function TransactionAEModal({
  open,
  onClose,
  onSave,
  editingTransaction,
  formData,
  onChange,
  cards = [],
  saving,
}) {
  const title = editingTransaction
    ? `Edit ${editingTransaction.strCode || `Transaction #${editingTransaction.nTransactionId}`}`
    : "Add Transaction";

  return (
    <ModalComponent
      open={open}
      onClose={onClose}
      title={title}
      type={editingTransaction ? "edit" : "add"}
      maxWidth="sm"
      onSave={onSave}
      saveLabel={
        saving
          ? "Saving…"
          : editingTransaction
            ? "Save changes"
            : "Create transaction"
      }
      saving={saving}
    >
      <FieldsComponent
        fields={getFormFields(cards, formData)}
        values={formData}
        onChange={onChange}
      />
      {/* The row is stamped server-side; show the moment in PHILIPPINE
          TIME so it reads the same on every machine. */}
      <Typography
        variant="caption"
        sx={{ display: "block", mt: 1, color: "var(--text-muted)" }}
      >
        {editingTransaction
          ? `Dated ${formatDateTimePH(editingTransaction.dttCreated)} (Philippine Time)`
          : `Will be dated ${formatDateTimePH(new Date())} (Philippine Time)`}
      </Typography>
    </ModalComponent>
  );
}
